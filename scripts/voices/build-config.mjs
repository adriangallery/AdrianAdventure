#!/usr/bin/env node
// A0.3 (plan SCUMM): regenera src/config/voice.config.ts entero y de forma determinista. Node puro, sin dependencias.
//
//   node scripts/voices/build-config.mjs [--check] [--root <dir>]
//
// Entrada: scripts/voices/fixed-keys.json (mapa anterior a A0.3, congelado), los mp3 de assets/audio/voice y la
// extracción de extract.mjs. Salida, en este orden:
//   VOICE_AUDIO_KEYS   las de fixed-keys.json y detrás, ordenados, los mp3 del disco que no estaban
//   VOICE_TEXT_MAP     las de fixed-keys.json y detrás, ordenadas por clave, las líneas extraídas con clip nuevo
//   NARRATOR_SEQUENCES las de fixed-keys.json y detrás '<escena>:narrative' de escenas con cinemática nueva
//                      cuyas líneas tienen todas su clip (la primera op narrative de la escena)
// --check no escribe: sale con 1 si el fichero no coincide (lo usa voice-coverage.mjs).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_ROOT, extractProject, resolve, loadFixed, listClips } from './extract.mjs';

export const CONFIG_FILE = 'src/config/voice.config.ts';

const HEADER = `/**
 * Voice configuration — maps dialogue text to voice audio keys.
 * Auto-generated by scripts/voices/build-config.mjs (A0.3) — do not edit manually.
 */

declare const __BUILD_HASH__: string;
const v = typeof __BUILD_HASH__ !== 'undefined' ? \`?v=\${__BUILD_HASH__}\` : '';
`;

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n').replace(/\r/g, '\\r')}'`;
const NEW_MARK = '=== A0.3: generado por el CI (scripts/voices) ===';

/** Construye el contenido del fichero. Devuelve { text, added: { audio, map, sequences } }. */
export function buildConfig({ fixed, files, resolved }) {
  const out = [HEADER, '/** All voice audio keys that need to be preloaded. */', 'export const VOICE_AUDIO_KEYS: string[] = ['];
  const known = new Set();
  for (const e of fixed.audioKeys) {
    if (typeof e === 'string') { out.push(`  ${q(e)},`); known.add(e); } else out.push(`  // ${e.comment}`);
  }
  const extraAudio = [...files].filter((k) => !known.has(k)).sort();
  if (extraAudio.length) out.push(`  // ${NEW_MARK}`, ...extraAudio.map((k) => `  ${q(k)},`));
  out.push('];', '', '/** Get the asset path for a voice key. */', 'export function voicePath(key: string): string {',
    '  return `assets/audio/voice/${key}.mp3${v}`;', '}', '', 'export const VOICE_TEXT_MAP: Array<{ text: string; key: string }> = [');
  for (const e of fixed.textMap) out.push(e.comment !== undefined ? `  // ${e.comment}` : `  { text: ${q(e.text)}, key: ${q(e.key)} },`);
  const newLines = resolved.filter((e) => e.kind === 'line' && e.status === 'clip').sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
  if (newLines.length) out.push(`  // ${NEW_MARK}`, ...newLines.map((e) => `  { text: ${q(e.text)}, key: ${q(e.key)} },`));
  out.push('];', '', 'export const NARRATOR_SEQUENCES: Record<string, string[]> = {');
  const seqs = { ...fixed.narratorSequences };
  const added = [];
  // escenas con cinemática sin secuencia: primera op narrative, solo si todas sus líneas tienen clip
  const narr = resolved.filter((e) => e.kind === 'narrative' && e.status !== 'fixed');
  const scenes = [...new Set(narr.map((e) => e.scene))].sort();
  for (const scene of scenes) {
    const first = Math.min(...narr.filter((e) => e.scene === scene).map((e) => e.index));
    const lines = narr.filter((e) => e.scene === scene && e.index === first);
    if (lines.every((e) => files.has(e.key))) { seqs[`${scene}:narrative`] = lines.map((e) => e.key); added.push(`${scene}:narrative`); }
  }
  for (const [k, keys] of Object.entries(seqs)) out.push(`  ${q(k)}: [${keys.map(q).join(', ')}],`);
  out.push('};', '');
  return { text: out.join('\n'), added: { audio: extraAudio, map: newLines.map((e) => e.key), sequences: added } };
}

export function buildFromDisk(root = DEFAULT_ROOT) {
  const fixed = loadFixed(root);
  const files = listClips(root);
  const resolved = resolve(extractProject(root), { fixed, files });
  return buildConfig({ fixed, files, resolved });
}

function main(argv) {
  let root = DEFAULT_ROOT;
  let check = false;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--check') check = true;
    else if (argv[i] === '--root') root = path.resolve(argv[++i]);
    else throw new Error(`argumento desconocido: ${argv[i]}`);
  }
  const { text, added } = buildFromDisk(root);
  const file = path.join(root, CONFIG_FILE);
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (check) {
    if (current === text) { console.log(`${CONFIG_FILE} al día`); return 0; }
    console.log(`${CONFIG_FILE} desactualizado: ejecuta node scripts/voices/build-config.mjs`);
    return 1;
  }
  if (current !== text) fs.writeFileSync(file, text);
  console.log(`${CONFIG_FILE}: ${current === text ? 'sin cambios' : 'regenerado'} (+${added.audio.length} claves de audio, +${added.map.length} textos, +${added.sequences.length} secuencias de narrador)`);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { process.exitCode = main(process.argv.slice(2)); } catch (e) { console.error(e.message); process.exitCode = 2; }
}
